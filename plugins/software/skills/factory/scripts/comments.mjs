#!/usr/bin/env node
// People's comments on a claimed ticket and its pull request, for its coordinator.
//
//   node comments.mjs fetch --ticket <n> --issue <n> [--pr <n>] --repo <owner/repo> [--root <project>]
//   node comments.mjs ack --ticket <n> <id>... [--root <project>]
//
// `fetch` only reads. It gathers four sources through `gh api`: the ticket's issue
// comments, the pull request's conversation, its reviews and its inline comments.
// It keeps a comment only when it is newer than the claim (`claimedAt`, fixed when
// the ticket was claimed), not yet acknowledged, not the factory's own (a body
// starting `## Factory`) nor the `triage` skill's (its disclaimer line), and written
// by someone with `admin`, `maintain` or `write` on the repository. Any other
// answer to the permission lookup, a bot's 404 included, makes the author
// untrusted: their text is counted, never printed. Ids are namespaced
// (`issue:`, `review:`, `inline:`); issue comments of the ticket and of the pull
// request share the `issue:` space.
//
// `ack` records ids as handled, through the locked update of resources.mjs. Run it
// only after the comments were handled.
//
// FACTORY_GH_FIXTURES=<dir> answers `gh api` from `<dir>/<endpoint with / as _>.json`
// (a missing file is a 404); the tests use it.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as res from "./resources.mjs";

const TRUSTED = new Set(["admin", "maintain", "write"]);
const TRIAGE_DISCLAIMER = "> *This was generated by AI during triage.*";

class NotFound extends Error {}

function ghList(endpoint) {
  const fixtures = process.env.FACTORY_GH_FIXTURES;
  if (fixtures) {
    const file = path.join(fixtures, endpoint.replace(/\//g, "_") + ".json");
    if (!fs.existsSync(file)) throw new NotFound(endpoint);
    return JSON.parse(fs.readFileSync(file, "utf8"));
  }
  const r = spawnSync("gh", ["api", "--paginate", endpoint, "--jq", ".[]"], { encoding: "utf8" });
  if (r.status !== 0) throw new Error(`gh api ${endpoint}: ${r.stderr.trim()}`);
  return r.stdout.split("\n").filter(Boolean).map((l) => JSON.parse(l));
}

function ghObject(endpoint) {
  const fixtures = process.env.FACTORY_GH_FIXTURES;
  if (fixtures) {
    const file = path.join(fixtures, endpoint.replace(/\//g, "_") + ".json");
    if (!fs.existsSync(file)) throw new NotFound(endpoint);
    return JSON.parse(fs.readFileSync(file, "utf8"));
  }
  const r = spawnSync("gh", ["api", endpoint], { encoding: "utf8" });
  if (r.status !== 0) throw new NotFound(`${endpoint}: ${r.stderr.trim()}`);
  return JSON.parse(r.stdout);
}

function trustedAuthor(repo, login, cache) {
  if (!cache.has(login)) {
    let ok = false;
    try {
      const p = ghObject(`repos/${repo}/collaborators/${encodeURIComponent(login)}/permission`);
      ok = TRUSTED.has(p.role_name) || TRUSTED.has(p.permission);
    } catch {
      ok = false;
    }
    cache.set(login, ok);
  }
  return cache.get(login);
}

export function fetchComments({ root, repo, ticket, issue, pr, now }) {
  const c = res.open(root, { now });
  const rec = res.getTicket(c, ticket);
  if (!rec.claimed || !rec.claimedAt) throw new res.Refused(`ticket ${ticket} is not claimed`);
  const since = Date.parse(rec.claimedAt);
  const acked = new Set(rec.acked);
  const raw = [];
  const add = (items, kind, where, time) => {
    for (const x of items) raw.push({ x, kind, where, at: x[time] });
  };
  if (issue) add(ghList(`repos/${repo}/issues/${issue}/comments`), "issue", "ticket", "created_at");
  if (pr) {
    add(ghList(`repos/${repo}/issues/${pr}/comments`), "issue", "pr", "created_at");
    add(ghList(`repos/${repo}/pulls/${pr}/reviews`), "review", "pr", "submitted_at");
    add(ghList(`repos/${repo}/pulls/${pr}/comments`), "inline", "pr", "created_at");
  }
  const skipped = { old: 0, acked: 0, factory: 0, triage: 0, empty: 0, untrusted: 0 };
  const cache = new Map();
  const seen = new Set();
  const comments = [];
  for (const { x, kind, where, at } of raw) {
    const id = `${kind}:${x.id}`;
    if (seen.has(id)) continue;
    seen.add(id);
    const body = String(x.body ?? "").trim();
    if (!at || Date.parse(at) <= since) skipped.old++;
    else if (acked.has(id)) skipped.acked++;
    else if (body.startsWith("## Factory")) skipped.factory++;
    else if (body.startsWith(TRIAGE_DISCLAIMER)) skipped.triage++;
    else if (kind === "review" && !body && x.state !== "CHANGES_REQUESTED") skipped.empty++;
    else if (!x.user?.login || !trustedAuthor(repo, x.user.login, cache)) skipped.untrusted++;
    else {
      const out = { id, kind, where, author: x.user.login, at, body, url: x.html_url };
      if (kind === "review") out.state = x.state;
      if (kind === "inline") Object.assign(out, { path: x.path, line: x.line ?? x.original_line ?? null });
      comments.push(out);
    }
  }
  comments.sort((a, b) => Date.parse(a.at) - Date.parse(b.at));
  return { ticket: Number(ticket), since: rec.claimedAt, comments, skipped };
}

function parseArgs(argv) {
  const pos = [];
  const opts = {};
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) opts[argv[i].slice(2)] = argv[i + 1]?.startsWith("--") ? true : argv[++i];
    else pos.push(argv[i]);
  }
  return { pos, opts };
}

export function run(argv) {
  const { pos, opts } = parseArgs(argv);
  const root = opts.root ?? process.cwd();
  const [cmd, ...ids] = pos;
  if (!opts.ticket) throw new res.Refused("--ticket <n> is required");
  if (cmd === "fetch") {
    if (!opts.repo) throw new res.Refused("--repo <owner/repo> is required");
    return fetchComments({ root, repo: opts.repo, ticket: opts.ticket, issue: opts.issue, pr: opts.pr, now: opts.now });
  }
  if (cmd === "ack") {
    const rec = res.ack(res.open(root, { now: opts.now }), opts.ticket, ids);
    return { ticket: rec.ticket, acked: rec.acked };
  }
  throw new res.Refused(`unknown command "${cmd ?? ""}"; use fetch or ack`);
}

if (process.argv[1] && fs.realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    process.stdout.write(JSON.stringify(run(process.argv.slice(2)), null, 2) + "\n");
  } catch (e) {
    process.stderr.write(`${e.message}\n`);
    process.exitCode = e instanceof res.Refused ? 2 : 1;
  }
}
